import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { api } from '../api.js'
import { Alert, Badge, Empty, Loading, Stat } from '../components/ui.jsx'
import { formatDate } from '../utils/format.js'

export default function Dashboard() {
  const [data, setData] = useState(null)
  const [error, setError] = useState('')

  useEffect(() => {
    api.listStudyPacks(50).then(setData).catch((e) => setError(e.message))
  }, [])

  const items = data?.items || []
  const completed = items.filter((p) => p.status === 'completed')
  const avg = completed.filter((p) => p.overall_score != null)
  const avgScore = avg.length ? (avg.reduce((s, p) => s + p.overall_score, 0) / avg.length).toFixed(1) : '–'
  const totalQuestions = completed.reduce((s, p) => s + p.mcq_count + p.short_count + p.long_count, 0)

  return (
    <>
      <div className="hero mb">
        <div>
          <h1>Welcome back</h1>
          <p>Turn lecture notes into topic summaries, key concepts, a full question bank with answer keys, and a quality report, all generated by prompt-engineered Gemini stages.</p>
        </div>
        <Link to="/upload" className="btn btn-light btn-lg">Upload a document</Link>
      </div>

      {error && <Alert>{error}</Alert>}
      {!data && !error && <Loading />}

      {data && (
        <>
          <div className="grid grid-4 mb">
            <Stat label="Documents processed" value={data.total_documents} hint="Uploaded and extracted" />
            <Stat label="Study packs" value={items.length} hint={`${completed.length} completed`} />
            <Stat label="Questions generated" value={totalQuestions} hint="MCQ + short + long" />
            <Stat label="Average quality score" value={avgScore} hint="Reviewer score out of 10" />
          </div>

          <div className="grid grid-2">
            <div className="card">
              <div className="card-title">
                <h2>Recent study packs</h2>
                <Link to="/packs" className="small">View all</Link>
              </div>
              {items.length === 0 ? (
                <Empty title="No study packs yet">Upload a PDF, PPTX, DOCX or TXT file to generate your first one.</Empty>
              ) : (
                items.slice(0, 6).map((p) => (
                  <div className="list-item" key={p.id}>
                    <div className="grow">
                      <div className="t">{p.title || p.filename}</div>
                      <div className="m">{p.filename} · {p.prompt_version.toUpperCase()} · {formatDate(p.created_at)}</div>
                    </div>
                    <Badge value={p.status} />
                    <Link className="btn btn-outline btn-sm" to={p.status === 'completed' ? `/packs/${p.id}` : `/generate/${p.id}`}>Open</Link>
                  </div>
                ))
              )}
            </div>

            <div className="card">
              <div className="card-title"><h2>Quick actions</h2></div>
              <div className="stages">
                <Link to="/upload" className="stage"><span className="num">1</span><span className="label">Upload lecture notes</span><span className="sub">PDF · PPTX · DOCX · TXT</span></Link>
                <Link to="/upload" className="stage"><span className="num">2</span><span className="label">Choose prompt version and difficulty</span><span className="sub">V1 · V2 · V3</span></Link>
                <Link to="/packs" className="stage"><span className="num">3</span><span className="label">Review, download and compare</span><span className="sub">PDF · DOCX</span></Link>
              </div>
            </div>
          </div>
        </>
      )}
    </>
  )
}
